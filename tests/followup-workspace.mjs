import fs from 'node:fs/promises';
import {makeEnv} from './neurodesk-regression.mjs';
const html=await fs.readFile(new URL('../index.html',import.meta.url),'utf8');
let checks=0;
function ok(name,value){if(!value)throw Error(name);checks++;}
const e=makeEnv(html),el=id=>e.doc.getElementById(id);
ok('patient mode has original chrome',!e.doc.body.classList.contains('nd-followup-workspace'));
e.ctx.toggleSymptom('headache');e.ctx.switchMode('doctor');e.ctx.switchDocStage('stage5_followup');
ok('stage five chrome active',e.doc.body.classList.contains('nd-followup-workspace'));
ok('five actual inputs retained',e.doc.querySelectorAll('.visit-fields label').length===5);
ok('file editor after inputs',el('vmEditor').parentNode.classList.contains('visit-editor'));
ok('preview in output desk',el('vmPreviewButton').parentNode.id==='ndPreviewAction');
ok('preview content in main column',el('vmPreview').parentNode.id==='ndPreviewArea');
ok('education approval in desk',el('eduConfirmed').parentNode.parentNode.parentNode.id==='ndEducationApproval');
ok('active navigation accessible',e.doc.querySelectorAll('#doctor5StageNav .nav-btn').filter(n=>n.getAttribute('aria-current')==='step').length===1);
el('visitDiagnosis').value='가상 설명 <script>실행 안 됨</script>';
el('visitReturn').value='가상 추적 계획';el('visitCaution').value='가상 주의사항';
el('visitIncludeVisuals').checked=false;
el('visitReviewed').checked=true;e.ctx.refreshVisitPrint();
el('eduConfirmed').checked=true;e.ctx.toggleEducationPrint();
ok('independent print approvals valid',!el('visitPrint').disabled&&!el('eduPrintButton').disabled);
el('vmPreviewButton').click();
const preview=el('vmPreview').innerHTML;
ok('real preview handler retained',preview.includes('가상 설명 &lt;script&gt;실행 안 됨&lt;/script&gt;'));
ok('no chrome in patient preview',!preview.includes('안내서 구성')&&!preview.includes('nd-output-desk'));
await e.ctx.printVisitSheet();
ok('dedicated output used',e.prints===1&&el('visitPrintSheet').innerHTML.includes('가상 추적 계획'));
ok('output no approval controls',!el('visitPrintSheet').innerHTML.includes('eduConfirmed'));
el('visitReviewed').checked=true;el('eduConfirmed').checked=true;
e.ctx.renderDoctorStage();
ok('rerender single education approval',e.doc.querySelectorAll('#eduConfirmed').length===1);
ok('rerender retains field values',el('visitReturn').value==='가상 추적 계획');
e.ctx.clearVisitDraft();
ok('clear handler empties inputs',el('visitDiagnosis').value==='');
ok('clear keeps single relocated approval',e.doc.querySelectorAll('#eduConfirmed').length===1&&el('ndEducationApproval').querySelector('#eduConfirmed'));
e.ctx.switchDocStage('stage4_scales');
ok('other stages retain original chrome',!e.doc.body.classList.contains('nd-followup-workspace'));
e.ctx.switchDocStage('stage5_followup');
ok('return stage restores layout',e.doc.body.classList.contains('nd-followup-workspace'));
e.ctx.resetPatientIntake();
ok('new patient exits special chrome',!e.doc.body.classList.contains('nd-followup-workspace'));
ok('new patient unchecks approvals',!el('visitReviewed').checked&&!el('eduConfirmed')?.checked);
ok('only one upload control after reset',e.doc.querySelectorAll('#vmFileInput').length===1);
console.log(JSON.stringify({workspaceChecks:checks,FAIL:0,scope:'DOM simulation; not a browser layout/printing test'},null,2));
